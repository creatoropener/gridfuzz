#!/usr/bin/env node
/**
 * Generates THIRD_PARTY_NOTICES.md from the production dependency tree.
 *
 * Reads package-lock.json to find every package that ships in the app (dev-only packages are
 * skipped), then reads each package's own package.json in node_modules for its licence and
 * homepage. Run `npm ci` first. Usage: npm run notices
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const own = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

function licenseOf(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (!l) return 'UNKNOWN';
  if (typeof l === 'string') return l;
  if (Array.isArray(l)) return l.map((x) => (typeof x === 'string' ? x : x.type)).join(' OR ');
  return l.type ?? 'UNKNOWN';
}

function repoOf(pkg) {
  const url = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url;
  const raw = pkg.homepage ?? url ?? '';
  return raw.replace(/^git\+/, '').replace(/\.git$/, '').replace(/^git:\/\//, 'https://').replace(/^ssh:\/\/git@/, 'https://');
}

const rows = [];
const missing = [];
for (const [path, meta] of Object.entries(lock.packages ?? {})) {
  if (!path.startsWith('node_modules/')) continue;
  if (meta.dev || meta.devOptional) continue; // not shipped
  const dir = join(root, path);
  const manifest = join(dir, 'package.json');
  if (!existsSync(manifest)) {
    missing.push(path);
    continue;
  }
  const pkg = JSON.parse(readFileSync(manifest, 'utf8'));
  rows.push({ name: pkg.name ?? path.replace(/^.*node_modules\//, ''), version: pkg.version ?? meta.version, license: licenseOf(pkg), url: repoOf(pkg) });
}
rows.sort((a, b) => a.name.localeCompare(b.name));

if (missing.length) {
  console.error(`Warning: ${missing.length} packages from package-lock.json are not installed (optional platform builds?). Run "npm ci" for a complete list.`);
}

const direct = new Set(Object.keys(own.dependencies ?? {}));
const byLicense = new Map();
for (const r of rows) byLicense.set(r.license, (byLicense.get(r.license) ?? 0) + 1);

const lines = [
  '# Third-party notices',
  '',
  `GridFuzz ${own.version} is licensed under **${own.license}** (see \`LICENSE\`). It bundles the open-source packages listed below.`,
  'HyperFormula is licensed under GPL-3.0-only, which is why GridFuzz is too.',
  '',
  '_Generated by `npm run notices` from `package-lock.json` and the installed packages. Do not edit by hand._',
  '',
  '## Licence summary',
  '',
  ...[...byLicense.entries()].sort((a, b) => b[1] - a[1]).map(([l, n]) => `- ${l}: ${n}`),
  '',
  '## Direct dependencies',
  '',
  '| Package | Version | Licence | Source |',
  '|---|---|---|---|',
  ...rows.filter((r) => direct.has(r.name)).map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.url} |`),
  '',
  '## All shipped packages (including transitive)',
  '',
  '| Package | Version | Licence |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  '',
  '## Fonts',
  '',
  'Inter and JetBrains Mono are bundled through `@fontsource-variable/*` under the SIL Open Font License 1.1.',
  '',
];
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
console.log(`Wrote THIRD_PARTY_NOTICES.md (${rows.length} packages, ${direct.size} direct).`);
